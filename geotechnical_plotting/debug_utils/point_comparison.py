"""
Point Comparison Utilities - Reusable tools for comparing plot data points.

This module provides generic utilities for extracting data points from debug logs
and comparing them between monolith and modular implementations. It is designed
to be parameter-agnostic and work for any monolith-to-modular conversion.

The MAIN EVENT of debugging is the point-to-point coordinate comparison.
A successful conversion must show 100% match on all coordinates.

Usage:
    from geotechnical_plotting.debug_utils.point_comparison import (
        extract_points_from_log,
        compare_point_lists,
        generate_comparison_report,
        run_full_comparison,
    )

    # Extract points from both log files
    modular_points = extract_points_from_log("logs/modular.log", pattern="MODULAR")
    monolith_points = extract_points_from_log("logs/monolith.log", pattern="MONOLITH")

    # Compare and get report
    report = compare_point_lists(monolith_points, modular_points)
    print_comparison_report(report)
"""

import re
import logging
from pathlib import Path
from typing import Dict, List, Tuple, Optional, Any, NamedTuple
from dataclasses import dataclass, field

logger = logging.getLogger(__name__)


# ═══════════════════════════════════════════════════════════════════════════
# 📊 DATA STRUCTURES
# ═══════════════════════════════════════════════════════════════════════════


@dataclass
class DataPoint:
    """
    Represents a single data point extracted from a log file.

    Attributes:
        location_id: Location identifier (e.g., 'BH1', 'TP01')
        depth: Depth value
        x_value: X coordinate value
        y_value: Y coordinate value
        investigation: Investigation name (optional)
        raw_line: Original log line for debugging
    """

    location_id: str
    depth: float
    x_value: float
    y_value: float
    investigation: Optional[str] = None
    raw_line: Optional[str] = None

    def to_tuple(self) -> Tuple[str, float, float, float]:
        """Return hashable tuple for comparison (loc, depth, x, y)."""
        return (self.location_id, self.depth, self.x_value, self.y_value)

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, DataPoint):
            return False
        return self.to_tuple() == other.to_tuple()

    def __hash__(self) -> int:
        return hash(self.to_tuple())


@dataclass
class FormationData:
    """
    Holds all data points for a single formation.

    Attributes:
        formation_name: Name of the geological formation
        points: List of data points
        source: Source identifier (MONOLITH or MODULAR)
    """

    formation_name: str
    points: List[DataPoint] = field(default_factory=list)
    source: str = ""


@dataclass
class ComparisonResult:
    """
    Results of comparing monolith vs modular data points.

    Attributes:
        formation_name: Formation being compared
        monolith_count: Number of points in monolith
        modular_count: Number of points in modular
        matched_count: Number of exactly matching points
        only_in_monolith: Points present only in monolith
        only_in_modular: Points present only in modular
        is_perfect_match: True if 100% match (THE GOAL)
    """

    formation_name: str
    monolith_count: int
    modular_count: int
    matched_count: int
    only_in_monolith: List[DataPoint] = field(default_factory=list)
    only_in_modular: List[DataPoint] = field(default_factory=list)

    @property
    def is_perfect_match(self) -> bool:
        """Check if this is a 100% perfect match."""
        return (
            self.monolith_count == self.modular_count
            and self.matched_count == self.monolith_count
            and len(self.only_in_monolith) == 0
            and len(self.only_in_modular) == 0
        )

    @property
    def match_percentage(self) -> float:
        """Calculate match percentage."""
        if self.monolith_count == 0:
            return 100.0 if self.modular_count == 0 else 0.0
        return (self.matched_count / self.monolith_count) * 100


