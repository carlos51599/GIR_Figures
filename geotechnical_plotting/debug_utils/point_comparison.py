def compare_point_lists(
    monolith_points: List[DataPoint],
    modular_points: List[DataPoint],
    formation_name: str = "Unknown",
) -> ComparisonResult:
    """
    Compare two lists of data points and identify matches/differences.

    THIS IS THE MAIN EVENT OF DEBUGGING.
    A successful monolith-to-modular conversion requires 100% match.

    Args:
        monolith_points: Points from monolith implementation
        modular_points: Points from modular implementation
        formation_name: Name of formation being compared

    Returns:
        ComparisonResult with match statistics and differences

    Example:
        >>> result = compare_point_lists(mono_points, mod_points, "KC UW")
        >>> print(f"Match: {result.match_percentage}%")
        Match: 100.0%
    """
    # Convert to sets of tuples for comparison
    mono_set = {p.to_tuple() for p in monolith_points}
    mod_set = {p.to_tuple() for p in modular_points}

    # Find matches and differences
    matched = mono_set & mod_set
    only_mono = mono_set - mod_set
    only_mod = mod_set - mono_set

    # Convert back to DataPoint objects for detailed reporting
    mono_lookup = {p.to_tuple(): p for p in monolith_points}
    mod_lookup = {p.to_tuple(): p for p in modular_points}

    return ComparisonResult(
        formation_name=formation_name,
        monolith_count=len(monolith_points),
        modular_count=len(modular_points),
        matched_count=len(matched),
        only_in_monolith=[mono_lookup[t] for t in only_mono],
        only_in_modular=[mod_lookup[t] for t in only_mod],
    )


def compare_formations(
    monolith_data: Dict[str, FormationData],
    modular_data: Dict[str, FormationData],
) -> Dict[str, ComparisonResult]:
    """
    Compare all matching formations between monolith and modular data.

    Args:
        monolith_data: Formations extracted from monolith log
        modular_data: Formations extracted from modular log

    Returns:
        Dictionary mapping formation names to ComparisonResult
    """
    results: Dict[str, ComparisonResult] = {}

    # Find common formations
    all_formations = set(monolith_data.keys()) | set(modular_data.keys())

    for formation in all_formations:
        mono_points = monolith_data.get(formation, FormationData(formation)).points
        mod_points = modular_data.get(formation, FormationData(formation)).points

        results[formation] = compare_point_lists(mono_points, mod_points, formation)

    return results


