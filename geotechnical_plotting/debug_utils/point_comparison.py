def run_full_comparison(
    monolith_log_path: str,
    modular_log_path: str,
    formation_filter: Optional[str] = None,
    verbose: bool = True,
) -> Dict[str, ComparisonResult]:
    """
    Run a complete point-to-point comparison between monolith and modular logs.

    This is the recommended entry point for comparing implementations.

    Args:
        monolith_log_path: Path to monolith debug log
        modular_log_path: Path to modular debug log
        formation_filter: Optional filter for specific formation
        verbose: If True, print detailed reports

    Returns:
        Dictionary of ComparisonResults by formation

    Example:
        >>> results = run_full_comparison(
        ...     "logs/monolith_mv.log",
        ...     "logs/modular_mv.log",
        ...     formation_filter="Kimmeridge"
        ... )
        >>> all_match = all(r.is_perfect_match for r in results.values())
    """
    logger.info(f"🔍 Starting point-to-point comparison...")
    logger.info(f"   Monolith: {monolith_log_path}")
    logger.info(f"   Modular:  {modular_log_path}")

    # Extract points from both logs
    monolith_data = extract_points_from_log(
        monolith_log_path, "MONOLITH", formation_filter
    )
    modular_data = extract_points_from_log(
        modular_log_path, "MODULAR", formation_filter
    )

    logger.info(f"   Found {len(monolith_data)} formations in monolith")
    logger.info(f"   Found {len(modular_data)} formations in modular")

    # Compare all formations
    results = compare_formations(monolith_data, modular_data)

    # Print reports if verbose
    if verbose:
        print_full_comparison_summary(results)

    return results


def quick_file_compare(
    monolith_points_file: str,
    modular_points_file: str,
    formation_name: str = "Comparison",
) -> ComparisonResult:
    r"""
    Quick comparison of two extracted points files.

    Useful for comparing files created by PowerShell extraction:
        Get-Content log.txt | Select-String -Pattern "\[M\]" > points.txt

    Args:
        monolith_points_file: Path to monolith points text file
        modular_points_file: Path to modular points text file
        formation_name: Name to use in report

    Returns:
        ComparisonResult

    Example:
        >>> result = quick_file_compare(
        ...     "logs/monolith_points.txt",
        ...     "logs/modular_points.txt",
        ...     "KC UW"
        ... )
        >>> print(f"Match: {result.is_perfect_match}")
    """
    mono_points = extract_points_from_text_file(monolith_points_file)
    mod_points = extract_points_from_text_file(modular_points_file)

    result = compare_point_lists(mono_points, mod_points, formation_name)
    print_comparison_report(result)

    return result
