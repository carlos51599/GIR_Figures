def print_comparison_report(result: ComparisonResult) -> None:
    """
    Print a detailed comparison report for a single formation.

    Args:
        result: ComparisonResult to report
    """
    print("\n" + "═" * 80)
    print(f"POINT-TO-POINT COMPARISON: {result.formation_name}")
    print("═" * 80)

    # Summary stats
    print(f"\n📊 Point Counts:")
    print(f"   Monolith: {result.monolith_count}")
    print(f"   Modular:  {result.modular_count}")
    print(f"   Matched:  {result.matched_count}")

    # Match percentage (THE MAIN EVENT)
    if result.is_perfect_match:
        print(
            f"\n✅ PERFECT MATCH: {result.match_percentage:.1f}% ({result.matched_count}/{result.monolith_count})"
        )
    else:
        print(
            f"\n❌ MISMATCH: {result.match_percentage:.1f}% ({result.matched_count}/{result.monolith_count})"
        )

        if result.only_in_monolith:
            print(f"\n   Points ONLY in Monolith ({len(result.only_in_monolith)}):")
            for p in result.only_in_monolith[:10]:  # Show first 10
                print(
                    f"      {p.location_id} | Depth={p.depth} | X={p.x_value} | Y={p.y_value}"
                )
            if len(result.only_in_monolith) > 10:
                print(f"      ... and {len(result.only_in_monolith) - 10} more")

        if result.only_in_modular:
            print(f"\n   Points ONLY in Modular ({len(result.only_in_modular)}):")
            for p in result.only_in_modular[:10]:  # Show first 10
                print(
                    f"      {p.location_id} | Depth={p.depth} | X={p.x_value} | Y={p.y_value}"
                )
            if len(result.only_in_modular) > 10:
                print(f"      ... and {len(result.only_in_modular) - 10} more")

    print("\n" + "═" * 80)


def print_full_comparison_summary(results: Dict[str, ComparisonResult]) -> None:
    """
    Print summary report for all formations.

    Args:
        results: Dictionary of ComparisonResults by formation
    """
    print("\n" + "═" * 80)
    print("FULL COMPARISON SUMMARY - POINT-TO-POINT COORDINATE CHECK")
    print("═" * 80)

    perfect_matches = []
    mismatches = []

    for formation, result in results.items():
        if result.is_perfect_match:
            perfect_matches.append(formation)
        else:
            mismatches.append((formation, result))

    # Summary counts
    total = len(results)
    print(f"\n📊 Overall: {len(perfect_matches)}/{total} formations match perfectly")

    # Perfect matches
    if perfect_matches:
        print(f"\n✅ Perfect Matches ({len(perfect_matches)}):")
        for f in perfect_matches:
            r = results[f]
            print(f"   - {f}: {r.matched_count}/{r.monolith_count} points")

    # Mismatches (need attention)
    if mismatches:
        print(f"\n❌ Mismatches ({len(mismatches)}):")
        for f, r in mismatches:
            print(
                f"   - {f}: {r.match_percentage:.1f}% ({r.matched_count}/{r.monolith_count})"
            )
            if r.only_in_monolith:
                print(f"     Missing from modular: {len(r.only_in_monolith)} points")
            if r.only_in_modular:
                print(f"     Extra in modular: {len(r.only_in_modular)} points")

    print("\n" + "═" * 80)

    # Final verdict
    if not mismatches:
        print("🎉 ALL FORMATIONS MATCH - CONVERSION SUCCESSFUL!")
    else:
        print("⚠️  CONVERSION NEEDS REVIEW - SEE MISMATCHES ABOVE")

    print("═" * 80 + "\n")


