def extract_points_from_log(
    log_path: str,
    source_pattern: str = "MODULAR|MONOLITH",
    formation_filter: Optional[str] = None,
) -> Dict[str, FormationData]:
    """
    Extract data points from a debug log file.

    This function parses log files generated by the debug logging utilities
    and extracts structured data points for comparison.

    Args:
        log_path: Path to the log file
        source_pattern: Regex pattern to identify source (MODULAR or MONOLITH)
        formation_filter: Optional filter to extract only specific formation

    Returns:
        Dictionary mapping formation names to FormationData objects

    Example:
        >>> points = extract_points_from_log("logs/modular.log", "MODULAR")
        >>> print(len(points["Kimmeridge Clay Formation (Weathered)"].points))
        255
    """
    log_file = Path(log_path)
    if not log_file.exists():
        raise FileNotFoundError(f"Log file not found: {log_path}")

    formations: Dict[str, FormationData] = {}
    current_formation: Optional[str] = None
    current_source: str = ""

    # Patterns for parsing log lines
    formation_pattern = re.compile(
        r"\[(MODULAR|MONOLITH)\].*(?:DEBUG|Plot Data Debug).*[:-]\s*(.+?)(?:\s*$|\s*\|)"
    )
    # Pattern for data point lines - handles both [M]/[m] and [MODULAR]/[MONOLITH] formats
    point_pattern = re.compile(
        r"\[(?:M|m|MODULAR|MONOLITH)\]\s*(\S+)\s*\|\s*Depth=([^\s|]+)\s*\|\s*X=([^\s|]+)\s*\|\s*Y=([^\s|]+)(?:\s*\|\s*Inv=(.+))?"
    )

    with open(log_file, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            # Check for formation header
            form_match = formation_pattern.search(line)
            if form_match:
                current_source = form_match.group(1)
                current_formation = form_match.group(2).strip()

                # Apply formation filter if specified
                if (
                    formation_filter
                    and formation_filter.lower() not in current_formation.lower()
                ):
                    current_formation = None
                    continue

                if current_formation and current_formation not in formations:
                    formations[current_formation] = FormationData(
                        formation_name=current_formation, source=current_source
                    )
                continue

            # Check for data point line
            point_match = point_pattern.search(line)
            if point_match and current_formation:
                try:
                    loc_id = point_match.group(1)
                    depth = _parse_numeric(point_match.group(2))
                    x_val = _parse_numeric(point_match.group(3))
                    y_val = _parse_numeric(point_match.group(4))
                    inv = point_match.group(5).strip() if point_match.group(5) else None

                    point = DataPoint(
                        location_id=loc_id,
                        depth=depth,
                        x_value=x_val,
                        y_value=y_val,
                        investigation=inv,
                        raw_line=line.strip(),
                    )
                    formations[current_formation].points.append(point)
                except (ValueError, TypeError) as e:
                    logger.warning(f"Failed to parse line: {line.strip()} - {e}")

    return formations


def extract_points_from_text_file(
    file_path: str,
    pattern: Optional[str] = None,
) -> List[DataPoint]:
    """
    Extract data points from a simple text file with one point per line.

    Useful for files created by PowerShell extraction like:
        [M] BH1 | Depth=5.0 | X=100 | Y=0.5

    Args:
        file_path: Path to text file
        pattern: Optional regex pattern for lines to include

    Returns:
        List of DataPoint objects
    """
    points: List[DataPoint] = []
    point_pattern = re.compile(
        r"\[(?:M|m|MODULAR|MONOLITH)\]\s*(\S+)\s*\|\s*Depth=([^\s|]+)\s*\|\s*X=([^\s|]+)\s*\|\s*Y=([^\s|]+)"
    )

    with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            if pattern and not re.search(pattern, line, re.IGNORECASE):
                continue

            match = point_pattern.search(line)
            if match:
                try:
                    points.append(
                        DataPoint(
                            location_id=match.group(1),
                            depth=_parse_numeric(match.group(2)),
                            x_value=_parse_numeric(match.group(3)),
                            y_value=_parse_numeric(match.group(4)),
                            raw_line=line.strip(),
                        )
                    )
                except (ValueError, TypeError):
                    continue

    return points


def _parse_numeric(value: str) -> float:
    """Parse a numeric value from string, handling N/A and nan."""
    value = value.strip()
    if value.lower() in ("n/a", "nan", "none", ""):
        return float("nan")
    return float(value)


